def solve(host, port):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.connect((host, int(port)))

    def query(pt_hex):
        # Read until prompt
        buf = b""
        while b"plaintext encoded as hex:" not in buf:
            chunk = s.recv(1024)
            if not chunk:
                break
            buf += chunk
        s.sendall(pt_hex.encode() + b"\n")
        # Read until leakage result
        resp = b""
        while b"\n" not in resp or b"leakage" not in resp:
            chunk = s.recv(1024)
            if not chunk:
                break
            resp += chunk
            if b"leakage result:" in resp and b"\n" in resp[resp.find(b"leakage result:"):]:
                break
        for line in resp.decode(errors='ignore').splitlines():
            if "leakage result:" in line:
                return int(line.split(":")[-1].strip())
        return 0

    key_bytes = []
    # For each byte position, query 32 different values
    for byte_pos in range(16):
        sample_size = 35
        observed = []
        for val in range(sample_size):
            pt = [0] * 16
            pt[byte_pos] = val
            pt_hex = bytes(pt).hex()
            leak = query(pt_hex)
            observed.append(leak)

        # Correlate with sbox[val ^ k] & 1
        best_k = None
        max_corr = -1
        obs_mean = sum(observed) / sample_size
        obs_dev = [x - obs_mean for x in observed]
        obs_std = math.sqrt(sum(d*d for d in obs_dev))

        for k in range(256):
            hyp = [(sbox[val ^ k] & 1) for val in range(sample_size)]
            hyp_mean = sum(hyp) / sample_size
            hyp_dev = [x - hyp_mean for x in hyp]
            hyp_std = math.sqrt(sum(d*d for d in hyp_dev))
            if hyp_std == 0 or obs_std == 0:
                continue
            cov = sum(obs_dev[i] * hyp_dev[i] for i in range(sample_size))
            corr = cov / (obs_std * hyp_std)
            if corr > max_corr:
                max_corr = corr
                best_k = k

        assert best_k is not None
        key_bytes.append(best_k)
        print(f"Byte {byte_pos:2d}: {hex(best_k)} (corr: {max_corr:.4f})")

    s.close()
    key_hex = bytes(key_bytes).hex()
    flag = f"academy{{{key_hex}}}"
    print("Recovered Key:", key_hex)
    print("Flag:", flag)
    return flag

