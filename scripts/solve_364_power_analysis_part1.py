hw = [bin(x).count('1') for x in range(256)]

def solve(host, port, num_traces=150):
    s = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
    s.connect((host, int(port)))

    def query(pt_bytes):
        pt_hex = pt_bytes.hex()
        buf = b""
        while b"plaintext encoded as hex:" not in buf:
            chunk = s.recv(1024)
            if not chunk:
                break
            buf += chunk
        s.sendall(pt_hex.encode() + b"\n")
        resp = b""
        while b"]\n" not in resp:
            chunk = s.recv(4096)
            if not chunk:
                break
            resp += chunk
        resp_str = resp.decode(errors='ignore')
        # Extract list inside brackets
        start = resp_str.find("[")
        end = resp_str.find("]", start)
        trace = json.loads(resp_str[start:end+1])
        return trace

    plaintexts = []
    traces = []
    print(f"Collecting {num_traces} traces from {host}:{port}...")
    for i in range(num_traces):
        pt = bytes([random.randint(0, 255) for _ in range(16)])
        tr = query(pt)
        plaintexts.append(pt)
        traces.append(tr)

    s.close()
    print("Trace collection complete. Computing CPA correlation...")

    N = len(traces)
    T = len(traces[0])

    t_means = [sum(traces[i][t] for i in range(N)) / N for t in range(T)]
    t_devs = [[traces[i][t] - t_means[t] for i in range(N)] for t in range(T)]
    t_stds = [math.sqrt(sum(d*d for d in t_devs[t])) for t in range(T)]

    key_bytes = []
    for byte_idx in range(16):
        best_k = None
        max_corr = -1
        for k in range(256):
            h = [hw[sbox[plaintexts[i][byte_idx] ^ k]] for i in range(N)]
            h_mean = sum(h) / N
            h_dev = [h[i] - h_mean for i in range(N)]
            h_std = math.sqrt(sum(d*d for d in h_dev))
            if h_std == 0:
                continue
            for t in range(300, 420, 2):
                if t_stds[t] == 0:
                    continue
                cov = sum(h_dev[i] * t_devs[t][i] for i in range(N))
                r = abs(cov / (h_std * t_stds[t]))
                if r > max_corr:
                    max_corr = r
                    best_k = k
        assert best_k is not None
        key_bytes.append(best_k)
        print(f"Byte {byte_idx:2d}: {hex(best_k)} (corr: {max_corr:.4f})")

    key_hex = bytes(key_bytes).hex()
    flag = f"academy{{{key_hex}}}"
    print("Recovered Key:", key_hex)
    print("Flag:", flag)
    return flag

