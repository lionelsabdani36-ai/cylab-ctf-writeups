#!/usr/bin/env python3
"""
Solver for Challenge 45: vault-door-6 (Reverse Engineering)
Reverses single-byte XOR key 0x55 on target byte array.
"""

def solve() -> str:
    my_bytes = [
        0x3b, 0x65, 0x21, 0xa , 0x38, 0x0 , 0x36, 0x1d,
        0xa , 0x3d, 0x61, 0x27, 0x11, 0x66, 0x27, 0xa ,
        0x21, 0x1d, 0x61, 0x3b, 0xa , 0x2d, 0x65, 0x27,
        0xa , 0x36, 0x33, 0x30, 0x30, 0x63, 0x63, 0x61,
    ]
    pass_bytes = [b ^ 0x55 for b in my_bytes]
    return f"academy{{{bytes(pass_bytes).decode()}}}"

if __name__ == "__main__":
    print("Flag:", solve())
