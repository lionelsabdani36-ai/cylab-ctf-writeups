hw = [bin(x).count('1') for x in range(256)]

def solve(traces_dir="/home/lionelsabdani36/.hermes/kanban/workspaces/t_367e8fc6/traces"):
    if not os.path.exists(traces_dir):
        # Extract traces.zip if needed
        zip_path = os.path.join(os.path.dirname(traces_dir), "traces.zip")
        if not os.path.exists(zip_path):
            url = "https://challenge-files.cylabacademy.net/library/1e97c5f7c124b947d11b357e93edeb76b336e870986a614930480d2ce9931027/traces.zip"
            urllib.request.urlretrieve(url, zip_path)
        with zipfile.ZipFile(zip_path, 'r') as z:
            z.extractall(os.path.dirname(traces_dir))

    files = sorted(glob.glob(os.path.join(traces_dir, "trace*.txt")))
    assert len(files) > 0, "No trace files found!"

    pts = []
    traces = []
    for f in files:
        with open(f) as fp:
            lines = fp.read().splitlines()
            pts.append(bytes.fromhex(lines[0].split(':')[1].strip()))
            traces.append(json.loads(lines[1].split(':', 1)[1].strip()))

    N = len(traces)
    T = len(traces[0])

    t_means = [sum(traces[i][t] for i in range(N)) / N for t in range(T)]
    t_devs = [[traces[i][t] - t_means[t] for i in range(N)] for t in range(T)]
    t_stds = [math.sqrt(sum(d*d for d in t_devs[t])) for t in range(T)]

    key_bytes = []
    for byte_idx in range(16):
        best_k = None
        max_corr = -1
        for k in range(256):
            h = [hw[sbox[pts[i][byte_idx] ^ k]] for i in range(N)]
            h_mean = sum(h) / N
            h_dev = [h[i] - h_mean for i in range(N)]
            h_std = math.sqrt(sum(d*d for d in h_dev))
            if h_std == 0:
                continue
            for t in range(300, 420, 2):
                if t_stds[t] == 0:
                    continue
                cov = sum(h_dev[i] * t_devs[t][i] for i in range(N))
                r = abs(cov / (h_std * t_stds[t]))
                if r > max_corr:
                    max_corr = r
                    best_k = k
        assert best_k is not None
        key_bytes.append(best_k)

    key_hex = bytes(key_bytes).hex()
    flag = f"academy{{{key_hex}}}"
    print("Key:", key_hex)
    print("Flag:", flag)
    return flag

